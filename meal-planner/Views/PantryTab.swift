import SwiftUI

enum PantryTab: String, CaseIterable, Identifiable {
    case shopping = "Shopping List"
    case inventory = "Pantry Inventory"
    var id: String { rawValue }
}

struct PantryShoppingView: View {
    @Bindable var store: MealStore
    @State private var currentTab: PantryTab = .shopping
    
    // Input fields for adding items
    @State private var newItemName: String = ""
    @State private var showAutoGeneratedAlert: Bool = false
    
    var body: some View {
        NavigationStack {
            Group {
                if currentTab == .shopping {
                    shoppingListView
                } else {
                    inventoryView
                }
            }
            .navigationBarTitleDisplayMode(.inline)
            .toolbar {
                // Puts the segmented picker directly in the center of the navigation bar:
                ToolbarItem(placement: .principal) {
                    Picker("View", selection: $currentTab) {
                        ForEach(PantryTab.allCases) { tab in
                            Text(tab.rawValue).tag(tab)
                        }
                    }
                    .pickerStyle(.segmented)
                    .frame(maxWidth: 280)
                }
                
                if currentTab == .shopping {
                    ToolbarItem(placement: .primaryAction) {
                        Button {
                            store.generateShoppingListFromWeekPlan()
                            showAutoGeneratedAlert = true
                        } label: {
                            Label("Auto-Populate", systemImage: "wand.and.stars")
                        }
                    }
                }
            }
        }
    }
    
    // MARK: - 1. Shopping List View
    private var shoppingListView: some View {
        List {
            // Quick Add Row
            Section {
                HStack {
                    TextField("Add grocery item...", text: $newItemName)
                    Button {
                        let trimmed = newItemName.trimmingCharacters(in: .whitespaces)
                        if !trimmed.isEmpty {
                            store.shoppingList.append(ShoppingItem(name: trimmed))
                            newItemName = ""
                        }
                    } label: {
                        Image(systemName: "plus.circle.fill")
                            .foregroundStyle(Color.accentColor)
                    }
                    .disabled(newItemName.trimmingCharacters(in: .whitespaces).isEmpty)
                }
            }
            
            // Items List
            Section {
                if store.shoppingList.isEmpty {
                    Text("No items on your shopping list! Tap the magic wand above to auto-generate from this week's meals.")
                        .font(.subheadline)
                        .foregroundStyle(.secondary)
                        .padding(.vertical, 8)
                } else {
                    ForEach($store.shoppingList) { $item in
                        HStack(spacing: 12) {
                            Button {
                                item.isChecked.toggle()
                            } label: {
                                Image(systemName: item.isChecked ? "checkmark.circle.fill" : "circle")
                                    .font(.title3)
                                    .foregroundStyle(item.isChecked ? Color.green : Color.secondary)
                            }
                            .buttonStyle(.plain)
                            
                            Text(item.name)
                                .strikethrough(item.isChecked)
                                .foregroundStyle(item.isChecked ? .secondary : .primary)
                            
                            Spacer()
                        }
                    }
                    .onDelete { indices in
                        store.shoppingList.remove(atOffsets: indices)
                    }
                }
            } header: {
                Text("To Buy (\(store.shoppingList.filter { !$0.isChecked }.count))")
            }
        }
    }
    
    // MARK: - 2. Inventory / Pantry View
    private var inventoryView: some View {
        List {
            // Quick Add Row
            Section {
                HStack {
                    TextField("Add pantry item...", text: $newItemName)
                    Button {
                        let trimmed = newItemName.trimmingCharacters(in: .whitespaces)
                        if !trimmed.isEmpty {
                            store.pantry.append(PantryItem(name: trimmed, quantity: 1))
                            newItemName = ""
                        }
                    } label: {
                        Image(systemName: "plus.circle.fill")
                            .foregroundStyle(Color.accentColor)
                    }
                    .disabled(newItemName.trimmingCharacters(in: .whitespaces).isEmpty)
                }
            }
            
            // Pantry Items with Steppers
            Section("Current Food Stock") {
                if store.pantry.isEmpty {
                    Text("Pantry is empty. Add ingredients you have at home.")
                        .font(.subheadline)
                        .foregroundStyle(.secondary)
                } else {
                    ForEach($store.pantry) { $item in
                        HStack {
                            VStack(alignment: .leading, spacing: 2) {
                                Text(item.name)
                                    .font(.body)
                                Text(item.category)
                                    .font(.caption2)
                                    .foregroundStyle(.secondary)
                            }
                            
                            Spacer()
                            
                            // +/- Stepper (from your outline!)
                            HStack(spacing: 12) {
                                Button {
                                    if item.quantity > 1 { item.quantity -= 1 }
                                } label: {
                                    Image(systemName: "minus.circle")
                                        .foregroundStyle(item.quantity > 1 ? Color.accentColor : Color.gray)
                                }
                                .buttonStyle(.plain)
                                
                                Text("\(item.quantity)")
                                    .font(.body.monospacedDigit().bold())
                                    .frame(minWidth: 20)
                                
                                Button {
                                    item.quantity += 1
                                } label: {
                                    Image(systemName: "plus.circle")
                                        .foregroundStyle(Color.accentColor)
                                }
                                .buttonStyle(.plain)
                            }
                        }
                    }
                    .onDelete { indices in
                        store.pantry.remove(atOffsets: indices)
                    }
                }
            }
        }
    }
}
